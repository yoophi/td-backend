func TestWorkflowStartHandoffReviewReplayAndUnstartHistory(t *testing.T) {
	h, p, session := issueSetup(t)
	base := "/v1/projects/" + p + "/issues"
	status, _, data := issueRequest(t, h, "POST", base, session, key(t), "", `{"title":"Workflow integration"}`)
	if status != 201 {
		t.Fatal(status, string(data))
	}
	id := issueFrom(t, data).ID
	path := base + "/" + id
	status, _, data = issueRequest(t, h, "POST", path+"/review", session, key(t), `"r-1"`, `{}`)
	if status != 400 {
		t.Fatal(status, string(data))
	}
	startKey := key(t)
	status, etag, first := issueRequest(t, h, "POST", path+"/start", session, startKey, `"r-1"`, `{"snapshot":{"branch":"main","dirty_files":0}}`)
	if status != 200 || etag != `"r-2"` || issueFrom(t, first).Status != domain.StatusInProgress {
		t.Fatal(status, etag, string(first))
	}
	status, replayedETag, data := issueRequest(t, h, "POST", path+"/start", session, startKey, `"r-1"`, `{"snapshot":{"dirty_files":0,"branch":"main"}}`)
	if status != 200 || replayedETag != etag || string(first) != string(data) {
		t.Fatal("start replay changed", status, string(data))
	}
	status, etag, data = issueRequest(t, h, "POST", path+"/unstart", session, key(t), `"r-2"`, `{}`)
	if status != 200 || etag != `"r-3"` || issueFrom(t, data).ImplementerSession != nil {
		t.Fatal(status, etag, string(data))
	}
	status, _, data = issueRequest(t, h, "POST", path+"/start", session, key(t), `"r-3"`, `{}`)
	if status != 200 {
		t.Fatal(status, string(data))
	}
	handoffKey := key(t)
	status, etag, first = issueRequest(t, h, "POST", path+"/handoffs", session, handoffKey, `"r-4"`, `{"done":["implemented"],"snapshot":{"commit_sha":"abc"}}`)
	if status != 201 || etag != `"r-5"` || issueFrom(t, first).Status != domain.StatusInReview {
		t.Fatal(status, etag, string(first))
	}
	var body struct {
		Data struct {
			Handoff         receiptcodec.HandoffDTO
			ReviewRequested bool `json:"review_requested"`
		}
	}
	if e := json.Unmarshal(first, &body); e != nil {
		t.Fatal(e)
	}
	if !body.Data.ReviewRequested || body.Data.Handoff.Remaining == nil || len(body.Data.Handoff.Done) != 1 {
		t.Fatal(string(first))
	}
	status, replayedETag, data = issueRequest(t, h, "POST", path+"/handoffs", session, handoffKey, `"r-4"`, `{"snapshot":{"commit_sha":"abc"},"done":["implemented"]}`)
	if status != 201 || replayedETag != etag || string(data) != string(first) {
		t.Fatal("handoff replay changed")
	}
	if e := h.store.Snapshot(context.Background(), func(read port.ReadSnapshot) error {
		history, e := read.Workflow().History(read.Context(), p, id)
		if e != nil {
			return e
		}
		if len(history) != 4 || history[0].Action != domain.ActionSessionCreated {
			t.Fatalf("history %+v", history)
		}
		handoff, e := read.Workflow().LatestHandoff(read.Context(), p, id)
		if e != nil {
			return e
		}
		if handoff == nil || handoff.Snapshot.CommitSHA != "abc" || handoff.ContentVersion != 2 {
			t.Fatalf("handoff %+v", handoff)
		}
		return nil
	}); e != nil {
		t.Fatal(e)
	}
}
func TestWorkflowParentCascadeRollsBackHandoffAndRetries(t *testing.T) {
	h, p, session := issueSetup(t)
	base := "/v1/projects/" + p + "/issues"
	create := func(title, parent string) string {
		t.Helper()
		status, _, data := issueRequest(t, h, "POST", base, session, key(t), "", fmt.Sprintf(`{"title":%q,"parent_id":%q,"type":"epic"}`, title, parent))
		if status != 201 {
			t.Fatal(status, string(data))
		}
		return issueFrom(t, data).ID
	}
	parent := create("Parent epic", "")
	children := []string{create("First child", parent), create("Second child", parent)}
	for _, id := range children {
		status, _, data := issueRequest(t, h, "POST", base+"/"+id+"/start", session, key(t), `"r-1"`, `{}`)
		if status != 200 {
			t.Fatal(status, string(data))
		}
	}
	status, _, data := issueRequest(t, h, "POST", base+"/"+children[0]+"/handoffs", session, key(t), `"r-2"`, `{}`)
	if status != 201 {
		t.Fatal(status, string(data))
	}
	inspect, e := sql.Open("sqlite", h.path)
	if e != nil {
		t.Fatal(e)
	}
	defer inspect.Close()
	// IDs are generated by the test; bind parameters are not permitted in trigger definitions.
	trigger := fmt.Sprintf(`CREATE TRIGGER reject_parent BEFORE UPDATE ON issues WHEN OLD.id='%s' BEGIN SELECT RAISE(ABORT,'parent failure'); END`, parent)
	if _, e = inspect.Exec(trigger); e != nil {
		t.Fatal(e)
	}
	op := key(t)
	path := base + "/" + children[1] + "/handoffs"
	status, _, data = issueRequest(t, h, "POST", path, session, op, `"r-2"`, `{}`)
	if status != 409 {
		t.Fatal(status, string(data))
	}
	if e = h.store.Snapshot(context.Background(), func(read port.ReadSnapshot) error {
		i, e := read.Issues().Get(read.Context(), p, children[1], false)
		if e != nil {
			return e
		}
		if i.Status != domain.StatusInProgress || i.Revision != 2 {
			t.Fatal("partial child committed")
		}
		handoff, e := read.Workflow().LatestHandoff(read.Context(), p, children[1])
		if e != nil {
			return e
		}
		if handoff != nil {
			t.Fatal("partial handoff committed")
		}
		return nil
	}); e != nil {
		t.Fatal(e)
	}
	if _, e = inspect.Exec(`DROP TRIGGER reject_parent`); e != nil {
		t.Fatal(e)
	}
	status, _, data = issueRequest(t, h, "POST", path, session, op, `"r-2"`, `{}`)
	if status != 201 {
		t.Fatal(status, string(data))
	}
	status, etag, data := issueRequest(t, h, "GET", base+"/"+parent, session, "", "", "")
	if status != 200 || etag != `"r-2"` || issueFrom(t, data).Status != domain.StatusInReview {
		t.Fatal(status, etag, string(data))
	}
}

func TestWorkflowBlockForceAndPassiveHandoff(t *testing.T) {
	h, p, session := issueSetup(t)
	base := "/v1/projects/" + p + "/issues"
	status, _, data := issueRequest(t, h, "POST", base, session, key(t), "", `{"title":"Blocking workflow"}`)
	if status != 201 {
		t.Fatal(status, string(data))
	}
	path := base + "/" + issueFrom(t, data).ID
	status, _, data = issueRequest(t, h, "POST", path+"/block", session, key(t), `"r-1"`, `{"reason":"waiting for input"}`)
	if status != 200 || issueFrom(t, data).Status != domain.StatusBlocked {
		t.Fatal(status, string(data))
	}
	status, _, data = issueRequest(t, h, "POST", path+"/start", session, key(t), `"r-2"`, `{}`)
	if status != 409 {
		t.Fatal(status, string(data))
	}
	status, _, data = issueRequest(t, h, "POST", path+"/start", session, key(t), `"r-2"`, `{"force":true,"snapshot":{"dirty_files":-1}}`)
	if status != 400 {
		t.Fatal(status, string(data))
	}
	status, _, data = issueRequest(t, h, "POST", path+"/start", session, key(t), `"r-2"`, `{"force":true}`)
	if status != 200 || issueFrom(t, data).Status != domain.StatusInProgress {
		t.Fatal(status, string(data))
	}
	status, etag, data := issueRequest(t, h, "POST", path+"/handoffs", session, key(t), `"r-3"`, `{"submit_review":false,"remaining":["more work"]}`)
	if status != 201 || etag != `"r-4"` || issueFrom(t, data).Status != domain.StatusInProgress {
		t.Fatal(status, etag, string(data))
	}
	status, _, data = issueRequest(t, h, "POST", path+"/review", session, key(t), `"r-4"`, `{}`)
	if status != 200 || issueFrom(t, data).Status != domain.StatusInReview {
		t.Fatal(status, string(data))
	}
}
